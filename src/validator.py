import os
import re


def is_valid_directory(path):
    """Проверяет, является ли путь допустимой директорией с правами на запись.

    Args:
        path (str): Путь к директории для проверки.

    Returns:
        bool: True, если путь существует, является директорией и доступен для записи,
        False в противном случае.
    """
    return os.path.isdir(path) and os.access(path, os.W_OK)


def is_valid_filename(filename):
    """Проверяет, является ли имя файла допустимым.

    Допустимые имена файлов могут содержать только буквы, цифры, подчеркивания,
    дефисы и точки. Соответствует стандартным соглашениям об именах файлов в UNIX.

    Args:
        filename (str): Имя файла для проверки.

    Returns:
        bool: True, если имя файла соответствует допустимому формату,
        False в противном случае.
    """
    return bool(re.match(r'^[\w\-.]+$', filename))